// Pouncity service worker (ticket 09). Registered when a person opts into
// reminders. The actual reminder messages are sent by the ticket-10 scheduler;
// this file just shows the notification and handles the click.

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = {};
  }
  const title = data.title || "Pouncity";
  const options = {
    body: data.body || "",
    tag: data.tag || "pouncity-reminder",
    data: { url: data.url || "/diary" },
  };
  event.waitUntil(self.registration.showNotification(title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || "/diary";
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
      for (const client of list) {
        if (client.url.includes(url) && "focus" in client) return client.focus();
      }
      if (clients.openWindow) return clients.openWindow(url);
    })
  );
});
